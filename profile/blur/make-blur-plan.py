#!/usr/bin/env python3
"""Writes Blur's install plan for the launcher (launcher/assets/plans/BLUR.json).

  profile/blur/make-blur-plan.py [OUT]

Every source is downloaded by the console at install time, pinned by SHA-256 and size;
nothing in the plan is the game's or a publisher's. Our own files go in as texts.
"""
import json, pathlib, sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "launcher/assets/plans/BLUR.json"

SOURCES = {
    "asi-loader": {
        "name": "Ultimate ASI Loader 9.7.4 (ThirteenAG, MIT)",
        "sha256": "952cebfc30d525afc2bdbaca954329d405ded3aa688a83027354dae14dfd5c5f",
        "size": 3910913,
        "url": "https://github.com/ThirteenAG/Ultimate-ASI-Loader/releases/download/v9.7.4/Ultimate-ASI-Loader.zip",
    },
    "amax-redirect": {
        "name": "amax-redirect.asi (Aib0t)",
        "sha256": "dae2d6b0946c4bf0413d24cff75e391df6bc5ba2f2ef457eb7fd1dfff6a9dacd",
        "size": 190976,
        "url": "https://github.com/Aib0t/amax-dns-asi/releases/download/latest/amax-redirect.asi",
    },
    "amax-client": {
        "name": "Amax client files 0.0.0.7",
        "sha256": "4ee93bc7676e4f9f03d2bd657300c47594fad5265fc15c2cd911f190567425c7",
        "size": 3300467,
        "url": "https://cs.amax-emu.com/amax_client_files.zip",
    },
}

# What earlier mod installs leave in a copy: left out of the install (the copy is not changed).
STRIP = ["dsound.dll", "dinput8.dll", "d3d9.dll", "scripts", "amax", "lua5.1.dll",
         "discord-rpc.dll", "blur_rpc.log"]

# amax_client_files.zip holds amax/ (a subtree) and three DLLs at its top level; an empty
# member means the source file itself, never "the whole zip", so each is placed by name.
AMAX_CLIENT = [
    {"source": "amax-client", "member": "amax/", "to": "amax/"},
    {"source": "amax-client", "member": "d3d9.dll", "to": "d3d9.dll"},
    {"source": "amax-client", "member": "lua5.1.dll", "to": "lua5.1.dll"},
    {"source": "amax-client", "member": "discord-rpc.dll", "to": "discord-rpc.dll"},
    # No amax/dxvk.dll: without it the d3d9.dll proxy above hands off to system32's
    # d3d9.dll, which in the bare prefix is our DXVK already.
]


# Blur saves its picture size in the Windows user's settings.xml once the player accepts its
# Graphics page, and from then on reads it before the desktop's size: kept to the profile's.
USER_FILES = [
    {
        "file": "AppData/Roaming/Bizarre Creations/Blur/settings.xml",
        "element": "shared_graphical_settings",
        "attributes": {"width": "{width}", "height": "{height}"},
    },
]

# A save the player puts in /data/sahin/saves/Blur (their own; none ships with Sahin), which a
# fresh install starts from. Blur's own save, once it has one, is never replaced.
USER_SEEDS = [
    {"from": "blursave", "file": "AppData/Roaming/Bizarre Creations/Blur/save/blursave"},
]


def text(name):
    return (HERE / name).read_text()


def plan():
    return {
        "schema": 1,
        "game": "BLUR",
        "title": "Blur",
        "release": "1.2",
        "prefix": "sahin",
        "_about": "Generated by profile/blur/make-blur-plan.py. Sources are downloaded on the console.",
        "sources": SOURCES,
        "strip": STRIP,
        "game_files": [{"source": "asi-loader", "member": "dinput8.dll", "to": "dsound.dll"}],
        "system_files": [],
        "patches": [],
        "ini": [],
        "texts": [{"to": "dxvk.conf", "body": text("dxvk.conf")}],
        "expect": {},
        "registry": {"machine": [], "user": []},
        "user_files": USER_FILES,
        "user_seeds": USER_SEEDS,
        "profile": {
            "id": "pb-blur",
            "name": "Sahin",
            "executable": "C:\\Games\\BLUR\\Blur.exe",
            "working_directory": "C:\\Games\\BLUR",
            "dll_overrides": "d3d9,dxgi=n;dsound=n,b",
            "width": 3840,
            "height": 2160,
            "runtime": {"fast_clock": "true", "shared_input": "true", "thread_scheduling": "true"},
            "after": "sahin.profile",
        },
        "pending": [],
        "options": [
            {
                "id": "online",
                "title": "Online through Amax",
                "description": "Multiplayer on the Amax community servers (amax-emu.com).",
                "default": True,
                "game_files": [{"source": "amax-redirect", "to": "scripts/amax-redirect.asi"}],
                "texts": [{"to": "scripts/amax-redirect.cfg", "body": text("amax-redirect.cfg")}],
            },
            {
                "id": "amax-client",
                "title": "Amax client extras",
                "description": "Amax's client: profile pictures, its Lua plugins and a 60 fps race cap.",
                "default": False,
                "game_files": AMAX_CLIENT,
                "dll_overrides": "d3d9=n",
            },
        ],
        "upgrades": [],
    }


if __name__ == "__main__":
    out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(plan(), indent=1) + "\n")
